/**
 * 三份帮助内容（左栏 / 右栏 / header）。
 *
 * ## 为什么单独一个文件
 *
 * 帮助文案是**最容易和界面脱节**的东西：改一次类别名、加一个分组，
 * 弹窗里还写着旧词，用户就更困惑了。所以：
 *   · 类别名、分组名一律**从 `classes.ts` 读**（单一事实来源）
 *   · 这里只补充"这个词是什么意思"（界面放不下的解释）
 *
 * ## 写作原则
 *
 * 用现场能懂的话，不用算法术语。比如不写"ExG 阈值"，写"颜色判据"；
 * 不写"连通域"，写"连成一片"。
 */

export interface HelpItem {
  term: string
  desc: string
}

export interface HelpSection {
  h: string
  items: HelpItem[]
}

export interface HelpDoc {
  title: string
  /** 顶部一句话：这个面板是干什么的 */
  intro: string
  sections: HelpSection[]
}

